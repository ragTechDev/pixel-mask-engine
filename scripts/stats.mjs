// Updates the "By the numbers" table in README.md: pnpm stats [--check]
// Counts what the built package exports and measures what a bundler ships for each part (minified + gzipped).
// --check changes nothing and fails if the counts in the README are out of date. It does not measure sizes, so it needs no bundler.
// Run `pnpm stats` after adding any icon, tile, object or avatar style so the README stays true.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { gzipSync } from "node:zlib";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const readme = join(root, "README.md");
const check = process.argv.includes("--check");
const START = "<!-- stats:start -->";
const END = "<!-- stats:end -->";

const lib = await import(pathToFileURL(join(root, "dist/index.js")).href).catch(() => {
  console.error("dist/index.js is missing. Run `pnpm build` first (or use `pnpm stats`, which builds).");
  process.exit(2);
});

const count = (table) => Object.keys(table).length;
const keysIn = (file, name) => {
  const body = new RegExp(`const ${name}\\s*=\\s*\\{([^}]*)\\}`).exec(readFileSync(join(root, file), "utf8"));
  if (!body) throw new Error(`Could not find ${name} in ${file}`);
  return [...body[1].matchAll(/(\w+)\s*:/g)].length;
};
const orientations = [...readFileSync(join(root, "src/avatar/masks/head.mask.ts"), "utf8").matchAll(/^ {4}(\w+): \[/gm)].length;
if (!orientations) throw new Error("Could not count head orientations in src/avatar/masks/head.mask.ts");

// A full outfit replaces the top and bottom, so clothing is the outfits plus every top and bottom pairing.
const outfits = count(lib.fullOutfitStyles) - 1;
const clothing = outfits + (count(lib.topStyles) * count(lib.bottomStyles));
const dims = {
  "head orientation": orientations,
  "skin tone": count(lib.skinPalettes),
  "front hair": count(lib.frontHairStyles),
  "back hair": count(lib.backHairStyles),
  "hair colour": count(lib.hairPalettes),
  "eye colour": count(lib.eyePalettes),
  "clothes colour": count(lib.clothesPalettes),
  clothing,
  shoes: count(lib.shoeStyles),
  "arm pose": keysIn("src/avatar/buildAvatar.ts", "ARM_POSES"),
  "leg pose": keysIn("src/avatar/buildAvatar.ts", "LEG_POSES")
};
const variations = Object.values(dims).reduce((a, b) => a * b, 1);

const counts = {
  icons: lib.iconIds.length,
  tiles: lib.tileIds.length,
  objects: lib.objectIds.length,
  avatarVariations: variations,
  avatarOptions: dims
};

// Bundle each part on its own from the built package, the way an app that imports only that part would.
async function bundled(use) {
  const esbuild = await import("esbuild").catch(() => {
    console.error("esbuild is not installed (it comes with tsup). Run `pnpm install`.");
    process.exit(2);
  });
  const result = await esbuild.build({
    stdin: { contents: `import * as m from "./dist/index.js"; globalThis.keep = [${use}];`, resolveDir: root },
    bundle: true,
    minify: true,
    treeShaking: true,
    format: "esm",
    write: false,
    logLevel: "silent"
  });
  return gzipSync(result.outputFiles[0].contents, { level: 9 }).length;
}

const entryGzip = (file) => {
  const seen = new Set();
  const collect = (f) => {
    if (seen.has(f)) return;
    seen.add(f);
    for (const m of readFileSync(join(root, "dist", f), "utf8").matchAll(/(?:from|import)\s*["']\.\/([^"']+)["']/g)) collect(m[1]);
  };
  collect(file);
  return gzipSync([...seen].map((f) => readFileSync(join(root, "dist", f), "utf8")).join("\n"), { level: 9 }).length;
};

const kb = (bytes) => `${(bytes / 1024).toFixed(2)} KB`;
const n = (v) => v.toLocaleString("en-US");

const measure = async () => ({
  icons: await bundled("m.buildIcon, m.iconIds"),
  tiles: await bundled("m.buildTile, m.tileIds"),
  objects: await bundled("m.buildObject, m.objectIds"),
  avatars: await bundled("m.buildAvatar"),
  everything: entryGzip("index.js"),
  canvas: entryGzip("canvas.js"),
  react: entryGzip("react.js")
});

const render = (sizes) => `${START}
<!-- counts: ${JSON.stringify(counts)} -->
Generated by \`pnpm stats\`. Sizes are minified and gzipped, for an app that imports only that part.

| Part | How many | Bundled size |
| --- | --- | --- |
| Icons | ${counts.icons} | ${kb(sizes.icons)} |
| Tiles | ${counts.tiles} | ${kb(sizes.tiles)} |
| Objects | ${counts.objects} | ${kb(sizes.objects)} |
| Avatars | up to ${n(variations)} variations | ${kb(sizes.avatars)} |
| Everything (core entry) | | ${kb(sizes.everything)} |
| Canvas helper | | ${kb(sizes.canvas)} |
| React components | | ${kb(sizes.react)} |

${END}`;

const text = readFileSync(readme, "utf8");
const start = text.indexOf(START);
const end = text.indexOf(END);
if (start < 0 || end < 0) {
  console.error(`README.md needs a ${START} ... ${END} block.`);
  process.exit(2);
}

if (check) {
  const recorded = /<!-- counts: (.*) -->/.exec(text.slice(start, end))?.[1];
  if (recorded === JSON.stringify(counts)) {
    console.log("README stats are up to date.");
    process.exit(0);
  }
  console.error("README stats are out of date. Run `pnpm stats` and commit the README.");
  console.error(`  README: ${recorded ?? "(none)"}\n  now:    ${JSON.stringify(counts)}`);
  process.exit(1);
}

writeFileSync(readme, text.slice(0, start) + render(await measure()) + text.slice(end + END.length));
console.log(`README stats updated: ${counts.icons} icons, ${counts.tiles} tiles, ${counts.objects} objects, ${n(variations)} avatar variations.`);
